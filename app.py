# 2. دالة تنظيف وقراءة المحادثات بالكامل
# ==========================================
def parse_whatsapp_chat(file_content):
    lines = file_content.decode('utf-8', errors='ignore').splitlines()
    messages = []
    
    for line in lines:
        line_str = line.strip()
        if not line_str or "<Media omitted>" in line_str or "Messages and calls are end-to-end encrypted" in line_str:
            continue
        
        if ":" in line_str:
            parts = line_str.split(":", 1)
            if len(parts) > 1 and len(parts[1].strip()) > 0:
                messages.append(parts[1].strip())
        else:
            if messages:
                messages[-1] += " " + line_str
                
    return messages

# ==========================================
# 3. دالة التحليل المدمج والهيكلية الرسمية
# ==========================================
def generate_combined_report(chat1_msgs, chat2_msgs, chat3_msgs, user_api_key):
    client = genai.Client(api_key=user_api_key.strip())
    
    # دمج كامل محتوى المحادثات (رفع حد القراءة لغرض التحليل الشامل)
    combined_text = "=== محتوى الجروب الأول ===\n" + "\n".join([f"- {m}" for m in chat1_msgs[:5000]]) + "\n\n"
    combined_text += "=== محتوى الجروب الثاني ===\n" + "\n".join([f"- {m}" for m in chat2_msgs[:5000]]) + "\n\n"
    combined_text += "=== محتوى الجروب الثالث ===\n" + "\n".join([f"- {m}" for m in chat3_msgs[:5000]])

    prompt = f"""
أنت خبير إستراتيجي في تحليل العمليات النفسية والرأي العام لجهاز أمني رسمي.
أمامك البيانات الكاملة المستخرجة من 3 قنوات/جروبات رصد:

---
{combined_text}
---

قم بتحليل كافة الرسائل المدخلة بدون استثناء وتوليد تقرير رسمي متكامل باللغة العربية بالتنسيق والهيكلية الرسمية المحددة أدناه بالضبط:

==================================================
جمهورية العراق
رئاسة الوزراء - جهاز الأمن الوطني العراقي
دائرة الأمن الوقائي ومكافحة التطرف
مديرية العمليات النفسية
==================================================

تقرير العمليات النفسية (الأسبوعي)

--------------------------------------------------
قائمة المحتويات:
1. الإيجاز العام
2. موقف العمليات النفسية المعادية وأبرز الشائعات والرأي العام والمرصد
3. أبرز مضامين الشائعات المرصودة والرسائل المراد إيصالها
4. النسبة المئوية لمضامين الشائعات المتداولة
5. موقف الرأي العام وجدول اهتمامات الرأي العام
6. تحليل الدعاية المضادة والجهات المروجة
7. موقف الخطاب الديني والاجتماعي
8. القراءة الاستشرافية والتهديدات المحتملة
9. المعالجات والتوصيات المقترحة
10. الجدول الشامل للتصنيف والمرصد
--------------------------------------------------

[ابدأ الآن بكتابة أجزاء التقرير بالتفصيل]:

### 1. الإيجاز العام:
ملخص تنفيذي مركز لأهم ما تم رصده خلال هذه الفترة في كافة المحادثات.

### 2. موقف العمليات النفسية المعادية وأبرز الشائعات والرأي العام والرصد:
تحليل دقيق لأبرز تحركات التضليل الإعلامي والحملات الموجهة عبر المنصات والمجموعات.

### 3. أبرز مضامين الشائعات المرصودة والرسائل التي أرادت إيصالها:
تحديد الشائعات الرئيسية، والغاية الأمنية أو النفسية من وراء ترويجها.

### 4. النسب المئوية لمضامين الشائعات المتداولة:
توزيع تقديري للمواضيع الشائعة (مثلاً: أمني %، اقتصادي %، سياسي %، خدمي %).

### 5. موقف الرأي العام وجدول اهتمامات الشارع:
عرض لأبرز القضايا التي تشغل الرأي العام العراقي حالياً بناءً على المحادثات.

### 6. تحليل الدعاية المضادة والجهات المروجة:
رصد الخطابات الموجهة والجهات أو المنصات التي تحاول إثارة الفتن أو الشائعات.

### 7. موقف الخطاب الديني والاجتماعي:
رصد التوجهات في الخطاب الديني أو العشائري أو الاجتماعي والتفاعل الميداني معها.

### 8. القراءة الاستشرافية:
توقع السيناريوهات القادمة والتهديدات الأمنية/النفسية المحتملة بناءً على مؤشرات الرصد.

### 9. المعالجات والتوصيات المقترحة:
خطوات عملية وتنفيذية مقترحة للحد من الآثار النفسية والشائعات وإدارة الرأي العام.

### 10. جدول الشائعات والرصد الشامل:
أنشئ جدول Markdown متكامل يحتوي على كل المواضيع والمرصودات:
| الرقم | الموضوع الرئيسي | نوع التصنيف (شائعة / رأي عام / رصد) | التقييم (إيجابي / سلبي / محايد) | المنصة / المصدر | مستوى التفاعل | المعالجة المقترحة |
"""

    response = client.models.generate_content(
        model='gemini-3.8-flash',
        contents=prompt
    )
    return response.text

