if st.button("🚀 توليد التقرير الأسبوعي الرسمي المدمج", type="primary", use_container_width=True):
    if not api_key:
        st.error("⚠️ يرجى إدخال مفتاح API الخاص بك في الشريط الجانبي أولاً.")
